def main() -> None:
    if FIXTURES_ROOT.exists():
        # Não apaga — fixtures devem ser imutáveis. Apenas reescreve.
        pass
    FIXTURES_ROOT.mkdir(parents=True, exist_ok=True)

    print(f"Gerando {len(FIXTURES)} fixtures em {FIXTURES_ROOT}/")
    for fx in FIXTURES:
        try:
            _write_fixture(fx["name"], fx["generator"], fx["expected"], ext=fx["ext"])
            print(f"  ✓ {fx['name']} (ext={fx['ext']})")
        except Exception as e:
            print(f"  ❌ {fx['name']}: {e}")

    # Escreve índice
    index = {
        "version": "1.0.0",
        "fixtures": [fx["name"] for fx in FIXTURES],
        "license": "All fixtures are synthetic (script-generated); no third-party audio.",
    }
    (FIXTURES_ROOT / "index.json").write_text(
        json.dumps(index, indent=2), encoding="utf-8"
    )
    print(f"\n✅ {len(FIXTURES)} fixtures gerados. Index: {FIXTURES_ROOT / 'index.json'}")


if __name__ == "__main__":
    main()
