FIXTURES_ROOT = Path("fixtures")
SAMPLE_RATE = 48000


def _write_wav(path: Path, pcm: np.ndarray, sr: int = SAMPLE_RATE) -> None:
    """Escreve PCM float32 como WAV int16 (compatível amplo)."""
    if pcm.dtype != np.float32:
        pcm = pcm.astype(np.float32)
    # Clipa para [-1, 1] antes de converter
    pcm = np.clip(pcm, -1.0, 1.0)
    pcm_i16 = (pcm * 32767).astype(np.int16)
    if pcm_i16.ndim == 1:
        pcm_i16 = pcm_i16.reshape(-1, 1)
    path.parent.mkdir(parents=True, exist_ok=True)
    wavfile.write(str(path), sr, pcm_i16)


def _hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _write_fixture(name: str, content_fn, expected: dict, ext: str = "wav") -> None:
    """Cria um fixture em fixtures/<name>/ com hash do conteúdo."""
    fixture_dir = FIXTURES_ROOT / name
    if fixture_dir.exists():
        shutil.rmtree(fixture_dir)
    fixture_dir.mkdir(parents=True)

    file_path = fixture_dir / f"audio.{ext}"
    content_fn(file_path)

    file_sha = _hash_file(file_path)
    expected_data = {
        "fixture_name": name,
        "fixture_sha256": file_sha,
        "expected_decision": expected["decision"],
        "expected_failed_analyzers": expected.get("failed_analyzers", []),
        "expected_findings": expected.get("findings", []),
        "license": "synthetic — generated by audio-suite scripts (no third-party audio)",
        "generator": "scripts/generate_fixtures.py",
    }
    (fixture_dir / "expected.json").write_text(
        json.dumps(expected_data, indent=2), encoding="utf-8"
    )


