"""Gera fixtures de mordida determinísticos para o Beta.

Cada fixture é gravado em fixtures/<sha256_short>/ com:
- audio.wav (ou .yaml/.json para casos não-áudio)
- expected.json (decision, failed_analyzers, fixture_sha256)

Adendo S2: fixtures são imutáveis — o hash do conteúdo faz parte do path.
"""
from __future__ import annotations

import hashlib
import json
