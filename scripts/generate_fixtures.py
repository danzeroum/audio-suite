def _gen_clean(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Senoide limpa que passa em todos os critérios."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    # Amplitude ~0.1 → ~-20 dBFS → próximo de -23 LUFS
    left = 0.1 * np.sin(2 * np.pi * 440 * t)
    right = 0.1 * np.sin(2 * np.pi * 440 * t + np.pi / 6)
    return np.stack([left, right], axis=1).astype(np.float32)


def _gen_clipped(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Senoide saturada — clipping intencional."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    left = 1.3 * np.sin(2 * np.pi * 440 * t)
    right = 1.3 * np.sin(2 * np.pi * 440 * t + np.pi / 4)
    pcm = np.stack([left, right], axis=1).astype(np.float32)
    return np.clip(pcm, -1.0, 1.0)


def _gen_true_peak_over(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Combinação de senoides para gerar true peak > -1 dBTP."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    sig = 0.6 * np.sin(2 * np.pi * 440 * t)
    sig += 0.4 * np.sin(2 * np.pi * 880 * t + np.pi / 3)
    sig += 0.15 * np.sin(2 * np.pi * 1760 * t + np.pi / 2)
    sig = sig / np.max(np.abs(sig)) * 0.95  # perto de 0 dBFS
    return np.stack([sig, sig * 0.95], axis=1).astype(np.float32)


def _gen_lufs_hot(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Senoide alta amplitude → LUFS acima do target."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    left = 0.6 * np.sin(2 * np.pi * 440 * t)
    right = 0.6 * np.sin(2 * np.pi * 440 * t + np.pi / 6)
    return np.stack([left, right], axis=1).astype(np.float32)


def _gen_inverted_polarity(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Estéreo com canal direito invertido."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    left = 0.2 * np.sin(2 * np.pi * 440 * t)
    right = -left  # polaridade invertida
    return np.stack([left, right], axis=1).astype(np.float32)


def _gen_mono(duration_s: float = 3.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Mono — para profile que requer estéreo."""
    frames = int(duration_s * sr)
    t = np.linspace(0, duration_s, frames, endpoint=False)
    sig = 0.1 * np.sin(2 * np.pi * 440 * t)
    return sig.reshape(-1, 1).astype(np.float32)


def _gen_silence(duration_s: float = 5.0, sr: int = SAMPLE_RATE) -> np.ndarray:
    """Silêncio de 5 segundos."""
    frames = int(duration_s * sr)
    return np.zeros((frames, 2), dtype=np.float32)


def _gen_with_email_tag(tmp_path: Path) -> Path:
    """WAV com tag de email (PII). Usa mutagen para gravar tag."""
    import tempfile
    pcm = _gen_clean()
    _write_wav(tmp_path, pcm)
    # Tenta gravar tag via mutagen
    try:
        from mutagen.wave import WAVE  # type: ignore
        w = WAVE(str(tmp_path))
        w.tags = {"CONTACT": "user@example.com", "ARTIST": "test"}
        w.save()
    except Exception:
        # Fallback: escreve um arquivo YAML como 'tags' lado a lado
        sidecar = tmp_path.with_suffix(".tags.yaml")
        sidecar.write_text("CONTACT: user@example.com\nARTIST: test\n")
    return tmp_path


